import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { randomUUID } from 'node:crypto';
import { PGlite } from '@electric-sql/pglite';

test('progress saves atomic immutable outlines and snapshots, rejects stale writes, and isolates academies', async () => {
 const db = new PGlite();
 try {
  await db.exec(`CREATE ROLE anon; CREATE ROLE authenticated; CREATE SCHEMA auth;
   CREATE TABLE auth.users(id uuid PRIMARY KEY);
   CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$ SELECT nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;`);
  for (const file of ['202609140001_normalized_reports.sql','202609160001_wrong_answers.sql','202609160002_handoffs.sql','202609170001_auth_workspaces.sql','202610130001_student_progress.sql']) await db.exec(readFileSync(new URL(`../supabase/migrations/${file}`,import.meta.url),'utf8'));
  await db.exec(readFileSync(new URL('../supabase/migrations/202610130002_progress_book_batch.sql',import.meta.url),'utf8'));
  await db.exec(readFileSync(new URL('../supabase/migrations/202610130003_progress_record_batch.sql',import.meta.url),'utf8'));
  const uid=randomUUID(), classId=randomUUID();
  await db.query('INSERT INTO auth.users VALUES($1)',[uid]);
  await db.query("SELECT set_config('request.jwt.claim.sub',$1,false)",[uid]);
  await db.exec("SET ROLE authenticated; SELECT cosmath_create_workspace('Progress');");
  await db.query("INSERT INTO cosmath_classes(id,name) VALUES($1,'Class')",[classId]);
  await db.query("INSERT INTO cosmath_students(id,class_id,name) VALUES('a',$1,'A')",[classId]);
  const book={id:randomUUID(),student_id:'a',title:'Book',curriculum:'2022',course:'중2',units:[{id:'u1',group:'식',name:'계산'},{id:'u2',group:'식',name:'방정식'}],states:{},version:0};
  await assert.rejects(db.query('SELECT cosmath_add_progress_books($1::jsonb)',[JSON.stringify([{...book,id:randomUUID()},{...book,id:randomUUID(),student_id:'missing'}])]),/Invalid student/);
  assert.equal((await db.query('SELECT * FROM cosmath_progress_books')).rows.length,0);
  const save=async (b,e=null)=>(await db.query('SELECT cosmath_save_progress($1::jsonb,$2::jsonb) value',[JSON.stringify(b),e && JSON.stringify(e)])).rows[0].value;
  const first=await save(book);
  const entry={id:randomUUID(),book_id:book.id,record_date:'2026-10-13',unit_ids:['u1'],scope:'p.1~5',homework:'p.6~8',due_date:'2026-10-15',memo:''};
  const second=await save({...first.book,states:{u1:'완료'}},entry);
  await assert.rejects(db.query('SELECT cosmath_save_progress_batch($1::jsonb)',[JSON.stringify([{book:second.book,entry:{...entry,id:randomUUID()}},{book:first.book,entry:{...entry,id:randomUUID()}}])]),/Progress changed/);
  assert.equal(second.book.version,2);
  assert.equal(second.entry.homework,'p.6~8');
  assert.deepEqual(first.entry.states,{});
  assert.deepEqual(second.entry.states,{u1:'완료'});
  await assert.rejects(save(first.book, {...entry,id:randomUUID()}),/Progress changed/);
  await assert.rejects(save({...second.book,units:[...book.units,{id:'u3',group:'',name:'추가'}]}),/Progress changed/);
  await assert.rejects(save({...second.book,states:{bad:'완료'}}),/Invalid state/);
  await assert.rejects(save(second.book,{...entry,id:randomUUID(),unit_ids:['bad']}),/Unknown unit/);
  assert.equal((await db.query('SELECT version FROM cosmath_progress_books')).rows[0].version,2);
  assert.equal((await db.query('SELECT * FROM cosmath_progress_entries')).rows.length,2);
  await db.exec('RESET ROLE');
  await db.exec(readFileSync(new URL('../supabase/migrations/202610130004_class_textbooks.sql',import.meta.url),'utf8'));
  await db.exec('SET ROLE authenticated');
  const migrated=(await db.query('SELECT * FROM cosmath_progress_books WHERE id=$1',[book.id])).rows[0];
  assert.ok(migrated.library_id);
  assert.deepEqual(migrated.states,{u1:'완료'});
  assert.deepEqual((await db.query('SELECT units_snapshot FROM cosmath_progress_entries WHERE id=$1',[entry.id])).rows[0].units_snapshot,book.units);
  const manage=async(action,b,ids=[])=>(await db.query('SELECT cosmath_manage_class_book($1,$2::jsonb,$3::jsonb) value',[action,JSON.stringify(b),JSON.stringify(ids)])).rows[0].value;
  const catalog=await manage('save',{id:randomUUID(),class_id:classId,title:'Class textbook',curriculum:'2022',course:'중2',units:book.units,total_pages:100,version:0});
  const [assigned]=await manage('assign',catalog,['a']);
  const pageSave=await save({...assigned,completed_page:50,states:{u1:'완료'}},{...entry,id:randomUUID(),book_id:assigned.id});
  assert.equal(pageSave.entry.total_pages_snapshot,100);
  assert.equal(pageSave.entry.completed_page,50);
  assert.deepEqual(pageSave.entry.units_snapshot,book.units);
  const edited=await manage('save',{...catalog,title:'Edited book',total_pages:200,units:[book.units[0]]});
  const updated=(await db.query('SELECT * FROM cosmath_progress_books WHERE id=$1',[assigned.id])).rows[0];
  assert.equal(updated.total_pages,200);
  assert.equal(updated.title,'Edited book');
  assert.equal((await db.query('SELECT total_pages_snapshot FROM cosmath_progress_entries WHERE id=$1',[pageSave.entry.id])).rows[0].total_pages_snapshot,100);
  await assert.rejects(save(pageSave.book),/Progress changed|Book changed/);
  await assert.rejects(manage('save',catalog),/Book changed/);
  await manage('delete',edited);
  assert.equal((await db.query('SELECT archived FROM cosmath_progress_books WHERE id=$1',[assigned.id])).rows[0].archived,true);
  assert.equal((await db.query('SELECT * FROM cosmath_progress_entries WHERE book_id=$1',[assigned.id])).rows.length,1);
  const other=randomUUID(); await db.exec('RESET ROLE'); await db.query('INSERT INTO auth.users VALUES($1)',[other]);
  await db.query("SELECT set_config('request.jwt.claim.sub',$1,false)",[other]);
  await db.exec("SET ROLE authenticated; SELECT cosmath_create_workspace('Other');");
  assert.equal((await db.query('SELECT * FROM cosmath_progress_books')).rows.length,0);
  assert.equal((await db.query('SELECT * FROM cosmath_progress_entries')).rows.length,0);
  assert.equal((await db.query('SELECT * FROM cosmath_class_books')).rows.length,0);
  await assert.rejects(save(second.book),/Invalid student|Book changed/);
  await db.query("SELECT set_config('request.jwt.claim.sub',$1,false)",[uid]);
  await db.exec('RESET ROLE'); await db.exec("DELETE FROM cosmath_students WHERE id='a'");
  assert.equal((await db.query('SELECT * FROM cosmath_progress_entries')).rows.length,0);
 } finally { await db.close(); }
});
